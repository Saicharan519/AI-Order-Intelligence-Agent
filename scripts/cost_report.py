"""Cost and latency report from the trace tables (T-10.4).

Every real LLM call is a row in trace.requests (kind = 'llm_call'). This groups them by
activity, with tokens, prompt-cache hits, cost, and per-call latency, and adds the API
request summary (scripts/trace_report.py). Test rows (config names starting with "test:")
are excluded. Writes eval/reports/cost_report.md.

Usage:
    python scripts/cost_report.py
"""

from __future__ import annotations

import sys

from orderintel.config import PROJECT_ROOT, get_settings
from orderintel.db.connect import connect_trace
from orderintel.trace.queries import summary

REPORT = PROJECT_ROOT / "eval" / "reports" / "cost_report.md"
CALIBRATION_USD = 0.000689  # M0b calibration calls, made before the ledger existed (progress.md)

ACTIVITY_SQL = """
SELECT CASE
         WHEN config_name LIKE 'eval:dev:%' OR config_name LIKE 'eval:test:%'
              THEN 'SQL evaluation (M5 ablation, M10 variance and comparison)'
         WHEN config_name LIKE 'eval:ask%' THEN 'Ask evaluation (M6)'
         WHEN config_name LIKE 'eval:investigate%' THEN 'Investigate evaluation (M7, M10)'
         WHEN config_name LIKE 'safety:%' THEN 'Safety suite (M8)'
         WHEN config_name LIKE 'api%' THEN 'API / UI (M9 onward)'
         ELSE config_name
       END                                                        AS activity,
       model,
       count(*)                                                   AS calls,
       sum(tokens_in)                                             AS tokens_in,
       sum(tokens_cache_hit)                                      AS cache_hit,
       sum(tokens_out)                                            AS tokens_out,
       sum(cost_usd)                                              AS cost,
       percentile_cont(0.5) WITHIN GROUP (ORDER BY latency_ms)    AS p50,
       percentile_cont(0.95) WITHIN GROUP (ORDER BY latency_ms)   AS p95,
       min(created_at)                                            AS first_at
FROM trace.requests
WHERE kind = 'llm_call' AND config_name NOT LIKE 'test:%'
GROUP BY 1, 2
ORDER BY min(created_at)
"""


def main() -> int:
    s = get_settings()
    with connect_trace() as conn:
        rows = conn.execute(ACTIVITY_SQL).fetchall()
    api = summary(days=3650)
    total = sum(float(r[6]) for r in rows)
    calls = sum(r[2] for r in rows)
    t_in = sum(r[3] for r in rows)
    hit = sum(r[4] for r in rows)
    lines = [
        "# Cost and latency report",
        "",
        "Generated by `scripts/cost_report.py` from `trace.requests` (one row per real LLM "
        "call; test rows excluded). Latency is per model call. Prices: DeepSeek, off-peak "
        "where the run was scheduled off-peak (`src/orderintel/llm/pricing.py`).",
        "",
        "| Activity | Model | Calls | Tokens in | Cache hits | Tokens out | Cost (USD) "
        "| p50 call | p95 call |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for activity, model, n, ti, ch, to, cost, p50, p95, _ in rows:
        lines.append(
            f"| {activity} | {model} | {n} | {ti:,} | {ch:,} ({100 * ch / max(ti, 1):.0f}%) | "
            f"{to:,} | {float(cost):.6f} | {p50 / 1000:.1f} s | {p95 / 1000:.1f} s |"
        )
    lines += [
        f"| **Total (ledger)** | | **{calls}** | **{t_in:,}** | "
        f"**{hit:,} ({100 * hit / max(t_in, 1):.0f}%)** | | **{total:.6f}** | | |",
        "",
        f"Project spend: ${total:.6f} in the ledger + ${CALIBRATION_USD:.6f} for the M0b "
        f"calibration = **${total + CALIBRATION_USD:.6f}** of the ${s.llm_total_cap_usd:.2f} cap "
        f"({100 * (total + CALIBRATION_USD) / s.llm_total_cap_usd:.1f}%).",
        "",
        "## API requests (whole question, all model calls and queries)",
        "",
    ]
    if api["requests"]:
        lines += [
            "| Requests | p50 | p95 | Cost per question | Requests with a validator rejection |",
            "|---|---|---|---|---|",
            f"| {api['requests']} | {api['p50_ms'] / 1000:.1f} s | {api['p95_ms'] / 1000:.1f} s | "
            f"${api['cost_per_question']:.5f} | {100 * api['rejection_rate']:.0f}% |",
            "",
            "Few API requests so far (the M9 end-to-end check); repeated questions are served "
            "from the response cache, which lowers both cost and latency. The per-question "
            "latency of the evaluations is reported in `ask_eval.md` (p50 2.8 s, p95 4.8 s).",
        ]
    else:
        lines.append("No API requests recorded yet.")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {REPORT}: {calls} calls, ${total:.6f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
