@lru_cache
def load_allowlist() -> dict:
    return json.loads(ALLOWLIST_FILE.read_text(encoding="utf-8"))


def view_columns() -> dict[str, dict[str, str]]:
    """{view: {column: sql_type}} for sqlglot's schema-aware qualification."""
    views = load_allowlist()["views"]
    return {
        v: {c: meta["type"] for c, meta in spec["columns"].items()} for v, spec in views.items()
    }
