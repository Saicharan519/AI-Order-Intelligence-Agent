"""Evaluation runner.

M3 provides the reference-only mode; model configurations (A-D) are added in M5.

    python eval/run_eval.py --refs-only [--review eval/golden/REVIEW.md]

Reference-only mode validates the golden set itself:
  * schema, category counts (8/14/12/14/6/6) and split sizes (40/20);
  * every reference and accepted alternative runs as oi_eval (read-only), returns at
    least one row, is not trivial (all NULL or a single zero), and takes under 2 seconds;
  * the test-split fingerprint matches eval/golden/test_split.sha256 (once frozen).
"""

from __future__ import annotations

import argparse
import sys
import time
from collections import Counter
from pathlib import Path

import psycopg

from orderintel.db.connect import connect_eval
from orderintel.evaluation.compare import normalise_value
from orderintel.evaluation.golden import (
    CATEGORY_COUNTS,
    SPLIT_COUNTS,
    TEST_HASH_FILE,
    GoldenItem,
    load_golden,
    split_fingerprint,
)

MAX_REF_SECONDS = 2.0
PREVIEW_ROWS = 6


def run_sql(conn: psycopg.Connection, sql: str) -> tuple[list[str], list[tuple], float]:
    started = time.perf_counter()
    with conn.transaction(force_rollback=True):
        cur = conn.execute(sql)
        rows = cur.fetchall()
        cols = [d.name for d in cur.description or []]
    return cols, rows, time.perf_counter() - started


def is_trivial(rows: list[tuple]) -> bool:
    values = [normalise_value(v) for row in rows for v in row]
    return all(v is None for v in values) or values in ([0.0], [False])


def check_structure(items: list[GoldenItem]) -> list[str]:
    problems = []
    cats = Counter(i.category for i in items)
    if dict(cats) != CATEGORY_COUNTS:
        problems.append(f"category counts {dict(cats)} != {CATEGORY_COUNTS}")
    splits = Counter(i.split for i in items)
    if dict(splits) != SPLIT_COUNTS:
        problems.append(f"split counts {dict(splits)} != {SPLIT_COUNTS}")
    for cat in CATEGORY_COUNTS:
        if not any(i.category == cat and i.split == "test" for i in items):
            problems.append(f"category {cat} has no test item")
    return problems


def check_fingerprint(items: list[GoldenItem]) -> str:
    current = split_fingerprint(items)
    if not TEST_HASH_FILE.exists():
        return f"test split NOT frozen yet (current fingerprint {current[:12]}...)"
    frozen = TEST_HASH_FILE.read_text(encoding="utf-8").split()[0]
    if frozen != current:
        raise SystemExit(
            "TEST SPLIT CHANGED since it was frozen. Revert the edit, or record a justified "
            "re-freeze in docs/progress.md."
        )
    return f"test split frozen and unchanged ({current[:12]}...)"


def fmt_cell(v: object) -> str:
    n = normalise_value(v)
    if isinstance(n, float):
        return f"{n:,.2f}".rstrip("0").rstrip(".") if not n.is_integer() else f"{int(n):,}"
    return "NULL" if n is None else str(n)


def preview(rows: list[tuple]) -> str:
    shown = ["; ".join(fmt_cell(v) for v in row) for row in rows[:PREVIEW_ROWS]]
    more = f" … (+{len(rows) - PREVIEW_ROWS} rows)" if len(rows) > PREVIEW_ROWS else ""
    return " / ".join(shown) + more


def refs_only(review_path: Path | None) -> int:
    items = load_golden()
    problems = check_structure(items)
    review_lines = [
        "# Golden set review",
        "",
        "Generated by `eval/run_eval.py --refs-only`. For each question: does the question make "
        "sense, is it fair, and does the reference answer look right? Out-of-scope items must "
        "be refused.",
        "",
        "| ID | Split | Category | Question | Reference answer | Accepted alternatives | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    slow = []
    with connect_eval(autocommit=True) as conn:
        for item in items:
            answers = []
            for k, sql in enumerate(item.references):
                label = "reference" if k == 0 else f"alternative {k}"
                try:
                    _, rows, secs = run_sql(conn, sql)
                except psycopg.Error as e:
                    problems.append(f"{item.id} {label}: {e.diag.message_primary}")
                    answers.append("ERROR")
                    continue
                if not rows:
                    problems.append(f"{item.id} {label}: empty result")
                elif is_trivial(rows):
                    problems.append(f"{item.id} {label}: trivial result {rows}")
                if secs > MAX_REF_SECONDS:
                    slow.append(f"{item.id} {label}: {secs:.2f}s")
                answers.append(preview(rows))
            ref = answers[0] if answers else "(refuse)"
            alts = " ‖ ".join(answers[1:]) or "—"
            notes = item.notes.replace("|", "/")
            review_lines.append(
                f"| {item.id} | {item.split} | {item.category} | {item.question} | {ref} | "
                f"{alts} | {notes} |"
            )
            status = "refuse" if not item.answerable else f"{len(item.references)} ref(s) ok"
            print(f"  {item.id:<10} {item.split:<4} {status:<14} {ref[:70]}")

    problems += [f"slow reference (> {MAX_REF_SECONDS}s): {s}" for s in slow]
    fingerprint_status = check_fingerprint(items)

    if review_path:
        review_path.write_text("\n".join(review_lines) + "\n", encoding="utf-8", newline="\n")
    n_refs = sum(len(i.references) for i in items)
    print(f"\n{len(items)} items, {n_refs} reference queries; {fingerprint_status}")
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print(f"  - {p}")
        return 1
    print("All references valid.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the golden-set evaluation")
    parser.add_argument("--refs-only", action="store_true", help="validate references only")
    parser.add_argument("--review", type=Path, help="write a review table (markdown)")
    parser.add_argument(
        "--freeze", action="store_true",
        help="record the test-split fingerprint (once, after the owner's review)",
    )
    args = parser.parse_args(argv)
    if args.freeze:
        if TEST_HASH_FILE.exists():
            parser.error(f"already frozen: {TEST_HASH_FILE}. Re-freezing needs a recorded reason.")
        fp = split_fingerprint(load_golden())
        TEST_HASH_FILE.write_text(f"{fp}  test split of questions.yaml\n", encoding="utf-8",
                                  newline="\n")
        print(f"Test split frozen: {fp}")
        return 0
    if not args.refs_only:
        parser.error("only --refs-only and --freeze are available until M5")
    return refs_only(args.review)


if __name__ == "__main__":
    sys.exit(main())
